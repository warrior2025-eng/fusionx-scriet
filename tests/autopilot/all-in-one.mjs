// Writes supabase/manual/autopilot_all_in_one.sql: the Autopilot migrations (0042 onwards) in order,
// in one transaction. Run after changing any of them:  node tests/autopilot/all-in-one.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../..");
const dir = path.join(root, "supabase/migrations");
const files = fs.readdirSync(dir).filter((f) => /^(004[2-9]|00[5-9]\d)_autopilot.*\.sql$/.test(f)).sort();
const out = [
  "-- FusionX Autopilot: every Autopilot migration in one file, for the Supabase SQL Editor.",
  `-- Contains: ${files.join(", ")}.`,
  "--",
  "-- Paste it all and press Run, once. It is one transaction: on the first error it stops and nothing is",
  "-- applied. Running it again changes nothing (everything is \"if not exists\" / \"create or replace\" /",
  "-- \"on conflict do nothing\"). Then run supabase/setup/autopilot_cron.sql once for the schedule.",
  "-- Generated by tests/autopilot/all-in-one.mjs; edit the migrations, not this file.",
  "",
  "begin;",
  "",
  ...files.flatMap((f) => [`-- ════════════════ ${f} ════════════════`, fs.readFileSync(path.join(dir, f), "utf8").trimEnd(), ""]),
  "commit;",
  "",
];
fs.mkdirSync(path.join(root, "supabase/manual"), { recursive: true });
fs.writeFileSync(path.join(root, "supabase/manual/autopilot_all_in_one.sql"), out.join("\n"));
console.log(`supabase/manual/autopilot_all_in_one.sql: ${files.join(", ")}`);
